import { readdir, stat, writeFile } from "node:fs/promises";
import { extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const source = join(root, "web-pictures");
const target = join(root, "backend", "hub", "picture_archive.py");
const extensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif"]);

async function collect(directory) {
  const rows = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const absolute = join(directory, entry.name);
    if (entry.isDirectory()) rows.push(...await collect(absolute));
    else if (entry.isFile() && extensions.has(extname(entry.name).toLowerCase())) {
      rows.push([relative(source, absolute).split("\\").join("/"), (await stat(absolute)).size]);
    }
  }
  return rows;
}

const records = (await collect(source)).sort((a, b) => a[0].localeCompare(b[0], "en", { numeric: true, sensitivity: "base" }));
await writeFile(target, `# Generated by scripts/generate-album-seed.mjs.\nPICTURE_ARCHIVE = ${JSON.stringify(records, null, 2)}\n`);
console.log(`Wrote ${records.length} album pictures to ${target}`);
