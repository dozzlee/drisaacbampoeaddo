import { readFile, readdir, writeFile } from "node:fs/promises";
import { extname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const picturesRoot = join(projectRoot, "web-pictures");
const outputFile = join(projectRoot, "js", "pictures.js");
const browserImageExtensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"]);

async function collectImages(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const images = [];

  for (const entry of entries) {
    const absolutePath = join(directory, entry.name);
    if (entry.isDirectory()) {
      images.push(...await collectImages(absolutePath));
    } else if (entry.isFile() && browserImageExtensions.has(extname(entry.name).toLowerCase())) {
      images.push(relative(projectRoot, absolutePath).split("\\").join("/"));
    }
  }

  return images;
}

function readPngDimensions(buffer) {
  if (buffer.length < 24 || buffer.toString("ascii", 1, 4) !== "PNG") return null;
  return { width: buffer.readUInt32BE(16), height: buffer.readUInt32BE(20) };
}

function readJpegDimensions(buffer) {
  if (buffer.length < 4 || buffer[0] !== 0xff || buffer[1] !== 0xd8) return null;
  const sizeMarkers = new Set([0xc0, 0xc1, 0xc2, 0xc3, 0xc5, 0xc6, 0xc7, 0xc9, 0xca, 0xcb, 0xcd, 0xce, 0xcf]);
  let offset = 2;

  while (offset + 8 < buffer.length) {
    if (buffer[offset] !== 0xff) {
      offset += 1;
      continue;
    }
    while (buffer[offset] === 0xff) offset += 1;
    const marker = buffer[offset];
    offset += 1;
    if (marker === 0xd8 || marker === 0xd9) continue;
    if (offset + 2 > buffer.length) return null;
    const segmentLength = buffer.readUInt16BE(offset);
    if (segmentLength < 2 || offset + segmentLength > buffer.length) return null;
    if (sizeMarkers.has(marker)) {
      return {
        width: buffer.readUInt16BE(offset + 5),
        height: buffer.readUInt16BE(offset + 3)
      };
    }
    offset += segmentLength;
  }

  return null;
}

async function readImageDimensions(imagePath) {
  const buffer = await readFile(imagePath);
  const extension = extname(imagePath).toLowerCase();
  if (extension === ".png") return readPngDimensions(buffer);
  if (extension === ".jpg" || extension === ".jpeg") return readJpegDimensions(buffer);
  return null;
}

const pictures = (await collectImages(picturesRoot)).sort((a, b) =>
  a.localeCompare(b, "en", { numeric: true, sensitivity: "base" })
);

const portraitPictures = [];
for (const picture of pictures) {
  const dimensions = await readImageDimensions(join(projectRoot, picture));
  if (dimensions && dimensions.height > dimensions.width) portraitPictures.push(picture);
}

const source = `/* Generated by scripts/generate-picture-manifest.mjs. */\nwindow.TRIBUTE_PICTURES = ${JSON.stringify(pictures, null, 2)};\nwindow.TRIBUTE_PORTRAIT_PICTURES = ${JSON.stringify(portraitPictures, null, 2)};\n`;
await writeFile(outputFile, source, "utf8");
console.log(`Wrote ${pictures.length} browser-compatible pictures and ${portraitPictures.length} portrait pictures to js/pictures.js`);
